import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('./', import.meta.url);
const tokens = JSON.parse(readFileSync(new URL('tokens.json', root), 'utf8'));
const aliases = { bgAlt: 'bg-2', surfaceAlt: 'surface-2', surfaceHover: 'surface-hover', brandAlt: 'brand-2', brandText: 'brand-text', brandAltText: 'brand-2-text', onStrong: 'on-strong', successText: 'success-text', errorText: 'error-text', warningText: 'warning-text' };
function palette(mode, indent = '  ') {
  const colors = tokens.colors[mode];
  return Object.entries(colors).map(([key, value]) => `${indent}--${aliases[key] ?? key}: ${key === 'shadow' ? `0 20px 40px ${value}` : value};`).concat([`${indent}--info: ${mode === 'dark' ? colors.brandAltText : colors.brand};`, `${indent}--danger: ${colors.error};`]).join('\n');
}
const scales = [['radii', 'radius'], ['spacing', 'space']].flatMap(([key, prefix]) => Object.entries(tokens[key]).map(([name, value]) => `  --${prefix}-${name}: ${value}px;`));
const fonts = Object.entries(tokens.typography).map(([name, value]) => `  --font-${name}: ${value / 16}rem;`);
const spacing = Object.keys(tokens.spacing).map(name => `  --spacing-${name === 'xxl' ? '2xl' : name}: var(--space-${name});`);
const motion = Object.entries(tokens.motion.duration).map(([name, value]) => `  --motion-${name}: ${value}ms;`);
const easing = Object.entries(tokens.motion.easing).map(([name, value]) => `  --ease-${name === 'inOut' ? 'in-out' : name}: ${value};`);
const css = `/* Generated by generate-css.mjs from tokens.json. */
:root { color-scheme: light dark;
${palette('light')}
}
:root[data-theme="light"] { color-scheme: light;
${palette('light')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${palette('dark', '    ')}
  }
}
:root[data-theme="dark"] { color-scheme: dark;
${palette('dark')}
}
:root {
${[...scales, ...fonts, ...spacing, ...motion, ...easing].join('\n')}
  --leading-display: 1.2;
  --leading-heading: 1.25;
  --leading-body: 1.5;
  --leading-compact: 1.35;
  --measure-title: 18ch;
  --measure-prose: 72ch;
  --brand-2-10: color-mix(in srgb, var(--brand-2) 10%, transparent);
  --is-mobile: none;
}
@media (max-width: 1023px) { :root { --is-mobile: block; } }
`;
const target = new URL('web.css', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== css) {
    console.error(`Token CSS is stale: run node ${fileURLToPath(import.meta.url)}`);
    process.exitCode = 1;
  }
} else writeFileSync(target, css);
